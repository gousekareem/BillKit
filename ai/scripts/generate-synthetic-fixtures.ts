/*
 * Writes the SYNTHETIC smoke-test set to evaluation/synthetic_smoke/.
 * These are computer-generated, fictional documents (see scripts/synthetic.ts).
 * They exercise the pipeline and evaluation harness end to end; they are NOT
 * the HR 20-image evaluation and say nothing about real-world accuracy.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NON_BILLS, RECEIPTS, degrade, renderPng, syntheticBlank, syntheticChatScreenshot, syntheticPhoto, type Degradation } from './synthetic.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'evaluation', 'synthetic_smoke');
const imgDir = path.join(root, 'images');
fs.mkdirSync(imgDir, { recursive: true });

const PLAN: Array<[number, Degradation]> = [
  [0, 'photo_on_table'], [0, 'shadow'], [1, 'perspective'], [1, 'blur'], [2, 'clean'], [2, 'rotated_90'],
  [3, 'noisy_jpeg'], [3, 'rotated_6'], [4, 'dark'], [4, 'low_res'],
];
const rows: string[][] = [];
const csvEsc = (v: string) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
let i = 1;
for (const [idx, kind] of PLAN) {
  const spec = RECEIPTS[idx]!;
  const buf = await degrade(await renderPng(spec), kind);
  const ext = kind === 'photo_on_table' || kind === 'perspective' || kind === 'noisy_jpeg' ? 'jpg' : 'png';
  const name = `S${String(i).padStart(2, '0')}_${spec.id}_${kind}.${ext}`;
  fs.writeFileSync(path.join(imgDir, name), buf);
  const t = spec.truth;
  rows.push([`S${String(i).padStart(2, '0')}`, name, 'bill', t.documentClass, t.merchant ?? '', t.date ?? '', t.total?.toString() ?? '', t.currency ?? '', t.category ?? '', kind === 'clean' ? 'easy' : 'medium', kind, 'synthetic (generated by ai/scripts/synthetic.ts)', 'SYNTHETIC — not a real bill']);
  i++;
}
const nonBills: Array<[string, Buffer, string]> = [
  ['selfie_or_photo', await syntheticPhoto(), 'jpg'],
  ['id_card', await renderPng(NON_BILLS[0]!), 'png'],
  ['chat_or_app_screenshot', await syntheticChatScreenshot(), 'png'],
  ['letter_or_form', await renderPng(NON_BILLS[1]!), 'png'],
  ['blank_page', await syntheticBlank(), 'png'],
];
for (const [cls, buf, ext] of nonBills) {
  const name = `S${String(i).padStart(2, '0')}_nonbill_${cls}.${ext}`;
  fs.writeFileSync(path.join(imgDir, name), buf);
  rows.push([`S${String(i).padStart(2, '0')}`, name, 'non_bill', cls, '', '', '', '', '', 'easy', 'clean', 'synthetic (generated by ai/scripts/synthetic.ts)', 'SYNTHETIC — fictional specimen']);
  i++;
}
const header = ['image_id', 'file_name', 'expected_class', 'expected_document_type', 'expected_merchant', 'expected_date', 'expected_total', 'expected_currency', 'expected_category', 'difficulty', 'conditions', 'source', 'notes'];
fs.writeFileSync(path.join(root, 'ground_truth.csv'), [header, ...rows].map((r) => r.map(csvEsc).join(',')).join('\n') + '\n');
console.log(`Wrote ${rows.length} synthetic images + ground_truth.csv to ${root}`);
